// States (incl. DC + territories) that have a functioning county-equivalent government to enumerate.
function listCountyStates() {
  return Object.keys(US_COUNTIES).sort();
}

// The distinctive place token — the county-equivalent name with its noun suffix stripped ("Alachua County"
// → "alachua", "Orleans Parish" → "orleans", "St. Louis city" → "st. louis"). Anchored to the END so mid-name
// words survive ("James City County" → "james city"). This is the coverage key + browse-leash token.
function placeKey(name) {
  return String(name || '')
    .toLowerCase()
    .replace(/\s+(county|parish|borough|census area|municipality|municipio|city|town|village|township)\.?$/i, '')
    .trim();
}

// A FUNCTIONAL DESCRIPTION of the county-equivalent's governing body — deliberately NOT a guess at its
// proper name.
//
// This used to synthesise a title from the place's suffix: every "X Parish" became "Parish Council of X
// Parish, Louisiana". The reasoning was sound as far as it went — the string only had to anchor a browser
// search, and the research pass would corroborate the real body. The flaw was that it did not STAY an
// internal search anchor. Target strings are written into `covered`, read back by the coverage report, and
// read aloud to Lucas — so a naming convention silently became a factual claim about how a jurisdiction is
// governed. It was frequently wrong: most Louisiana parishes are run by a POLICE JURY, not a parish
// council (her own research surfaced Acadia/Calcasieu/Bossier Police Juries and the Caddo Parish
// Commission while the worklist insisted all 64 were "Parish Councils"), and titles vary just as wildly
// elsewhere (TX "Commissioners Court", IL "County Board", AK "Borough Assembly").
//
// So describe the body by its FUNCTION, which is true of every jurisdiction, and let research discover the
// name. We deliberately do NOT hard-code per-state titles instead: Louisiana alone is mixed parish-by-
// parish, so any table would re-introduce the same fabrication with more confidence behind it.
//
// The place token still rides along, so the browse leash and the coverage key are unchanged.
function bodyLabel(name) {
  const n = String(name || '');
  if (/\b(?:Municipality|municipio|city|town|village)$/i.test(n)) return 'the municipal governing body';
  return 'the governing body';
}

// ─── VALIDATION SHAPE (leash slice B — Lucas 2026-07-29) ─────────────────────────────────────────
// "The pass should be validating all government officials at all levels and should be more of an idle
// task." The autonomic sweep's job is ROSTER VALIDATION: confirm who currently holds every elected
// office, corroborate once, flag what changed — never the per-person A-grade-contact dossier grind
// that owned the browser for days per state. One shared facet plan + one goal builder so every
// elected tier validates the same way (drift-proof). The deep-dossier machinery still exists for
// DIRECTED asks (main.js single-target dossier path) — it just is not the idle sweep's default.
// Facets are SHORT, content-shaped labels on purpose (boot118 finding): the coverage detector
// (canvas_emit.coveredFacets) credits a facet only when ≥50% of its keywords appear in the
// deliverable — a facet written as an INSTRUCTION ("ballotpedia-class reference", county-only
// examples) can never be credited by correct city prose, so real work was logged as FALSE
// ABSENCE (CT 1 → RI 3 unfound, climbing). The discipline lives in validationGoal below, which
// rides every pass prompt; the facet text is what the RESULT will actually talk about.
const VALIDATION_FACETS = [
  'current roster — every officeholder named, with office and seat',
  'corroborated against an independent source',
  'changes — vacancies, appointments, upcoming elections',
  'official contact point — office address, phone, website',
];

function validationGoal(scope) {
  return `VALIDATE the elected officials of ${scope} — confirm WHO currently holds every elected office `
    + `against the official government source, cross-check once against an independent source (news, a `
    + `ballotpedia-class reference, or the state election authority), and flag vacancies, changes, and `
    + `discrepancies. This is a roster VALIDATION sweep, not a dossier: capture officeholder names, `
    + `offices, and the body's public contact point (the office's door — address, phone, website — `
    + `never a per-person contact hunt), then MOVE ON. Anything ambiguous or contested gets flagged `
    + `for deeper follow-up rather than ground out here.`;
}

// Enumerate the county-commission worklist for a state → researchable target strings. Each names the
// JURISDICTION and describes its governing body functionally ("the governing body of Alachua County,
// Florida") rather than asserting a title we have not verified; the pass researches that body and reports
// its real name. The county + state tokens keep the browse leash on-domain.
function countyCommissionTargets(stateCode) {
  const code = String(stateCode || '').toUpperCase();
  const st = US_COUNTIES[code];
  if (!st || !st.counties || !st.counties.length) return [];
  return st.counties.map((name) => `${bodyLabel(name)} of ${name}, ${st.name}`);
}

// A county-commission beat descriptor (the shape the registry holds one of per state, and seedBeatRun
// consumes). `enumerate()` returns the worklist; `universeSize()` is the coverage denominator (X / N).
function countyCommissionBeat(stateCode) {
  const code = String(stateCode || '').toUpperCase();
  const st = US_COUNTIES[code];
  const stateName = (st && st.name) || code;
  const noun = (st && st.noun) || 'county';
  const nounPlural = noun === 'parish' ? 'parishes' : noun === 'municipio' ? 'municipios' : `${noun === 'borough' ? 'boroughs' : 'counties'}`;
  const targets = countyCommissionTargets(code);
  return {
    id: `county-commissions-${code.toLowerCase()}`,
    parentBeat: 'elected-officials',
    kind: 'entity',                          // roster of governing bodies + their members
    stateCode: code,
    ladderRung: 3,                           // state ladder: after the legislature + capital/major cities
    // VALIDATE depth (slice B — was 'dossier'): confirm the board + county row offices, corroborate, flag
    // changes, move on. The dossier grind (2026-07-18) is what walked every county in the country and
    // owned the browser; directed asks still get full dossiers via the single-target path.
    depth: 'validate',
    facets: VALIDATION_FACETS,
    goal: validationGoal(`every ${noun} in ${stateName} — all ${targets.length} ${nounPlural}, each with its `
      + `governing board AND the other county-elected offices (sheriff, clerk, assessor, treasurer, `
      + `district attorney, elected judges)`),
    enumerate: () => targets,
    universeSize: () => targets.length,
  };
}

// Every county-commission sub-beat under the elected-officials parent (one per county-governing state), sorted
// by state code. This is the decomposition the scheduler draws from.
function countyCommissionSubBeats() {
  return listCountyStates().map((code) => countyCommissionBeat(code));
}

// --- MUNICIPAL tier (elected-officials granularity: city/town/village governments) --------------------

function listPlaceStates() { return Object.keys(US_PLACES).sort(); }

// The TIER of an incorporated place's governing body — see bodyLabel for why this describes rather than
// names. Census gives us the place TYPE authoritatively, so "municipal" is a fact we hold; the body's
// actual title is not ("City Council" vs "Board of Aldermen" vs "Common Council" vs "City Commission",
// and New England towns run on Select Boards, not Town Councils). Research reports the real one.
function placeBodyLabel(name) {
  const n = String(name || '');
  if (/\btownship$/i.test(n)) return 'the township governing body';
  return 'the municipal governing body';
}
// Strip the trailing Census type word from a place name for display ("Birmingham city" → "Birmingham").
// "(balance)" is Census bookkeeping on the consolidated-government rows ("Indianapolis city (balance)")
// — never part of the government's name, so it goes first, then the type word behind it can strip too.
function placeDisplayName(name) {
  return String(name || '')
    .replace(/\s*\(balance\)$/i, '')
    .replace(/\s+(city|town|village|borough|township|municipality|pueblo)$/i, '').trim();
}

// Resolve a plain city name ("Louisville") to its Census gazetteer entry ("Louisville/Jefferson County
// metro government (balance)"). Exact display/raw match wins; else the first name that CONTINUES the
// sought city with a separator (space / "/" / "-") — which is how the consolidated-government and
// "(balance)" forms appear — so "Charleston" never absorbs "North Charleston". Null = not an
// incorporated place in this state (the caller drops it; research would corroborate anyway).
function matchPlace(stateCode, cityName) {
  const st = US_PLACES[String(stateCode || '').toUpperCase()];
  const want = String(cityName || '').toLowerCase().trim();
  if (!st || !st.places || !want) return null;
  let prefix = null;
  for (const name of st.places) {
    const raw = String(name).toLowerCase();
    const disp = placeDisplayName(name).toLowerCase();
    if (raw === want || disp === want) return name;
    if (!prefix && [raw, disp].some((c) => c.startsWith(`${want} `) || c.startsWith(`${want}/`) || c.startsWith(`${want}-`))) prefix = name;
  }
  return prefix;
}

// The LADDER-HEAD gazetteer names for a state: capital first (the seat of the government the ladder
// descends from), then the largest cities, resolved + deduped. These are CLAIMED by the capital-cities
// rung, and municipalTargets excludes them so the two worklists stay disjoint (no double coverage).
function ladderHeadNames(stateCode) {
  const code = String(stateCode || '').toUpperCase();
  const def = US_CAPITAL_CITIES[code];
  if (!def) return [];
  const seen = new Set(), out = [];
  for (const w of [def.capital, ...(def.large || [])].filter(Boolean)) {
    const m = matchPlace(code, w);
    if (m && !seen.has(m)) { seen.add(m); out.push(m); }
  }
  return out;
}

// Enumerate the municipal worklist for a state → "<body> of <place>, <state>" (e.g. "City Council of
// Birmingham, Alabama", "Town Council of Autaugaville, Alabama"). EXCLUDES the ladder head (capital +
// major cities) — those belong to the capital-cities rung, walked first.
function municipalTargets(stateCode) {
  const code = String(stateCode || '').toUpperCase();
  const st = US_PLACES[code];
  if (!st || !st.places || !st.places.length) return [];
  const head = new Set(ladderHeadNames(code));
  return st.places.filter((name) => !head.has(name)).map((name) => `${placeBodyLabel(name)} of ${placeDisplayName(name)}, ${st.name}`);
}

// --- CAPITAL + MAJOR CITIES rung (the ladder head — walked right after the state government) ------

function capitalCityTargets(stateCode) {
  const code = String(stateCode || '').toUpperCase();
  const st = US_PLACES[code];
  if (!st) return [];
  return ladderHeadNames(code).map((name) => `${placeBodyLabel(name)} of ${placeDisplayName(name)}, ${st.name}`);
}

function capitalCityBeat(stateCode) {
  const code = String(stateCode || '').toUpperCase();
  const st = US_PLACES[code];
  const stateName = (st && st.name) || code;
  const targets = capitalCityTargets(code);
  const cities = ladderHeadNames(code).map((n) => placeDisplayName(n));
  return {
    id: `capital-cities-${code.toLowerCase()}`,
    parentBeat: 'elected-officials',
    kind: 'entity',
    stateCode: code,
    ladderRung: 2,                           // right after the state legislature, before the counties
    depth: 'validate',
    facets: VALIDATION_FACETS,
    goal: validationGoal(`the capital and major cities of ${stateName} — ${cities.join(', ') || 'none on record'} `
      + `(${targets.length} city government(s): mayor, council, and city-elected offices)`),
    enumerate: () => targets,
    universeSize: () => targets.length,
  };
}

function capitalCitySubBeats() { return listPlaceStates().map((code) => capitalCityBeat(code)); }

// A municipal-government beat descriptor for a state (dossier depth, like county). Covers the city's elected
// council + mayor + the other city-elected offices, with the same A-grade-contact + meetings/charter/history
// discipline. Huge worklists (TX ~1,220, IL ~1,300) — the scheduler slices + rotates them like any beat.

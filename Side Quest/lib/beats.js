// Authoritative, bundled enumeration: { <USPS>: { name, noun, counties: [official county-equivalent names] } }.
// "noun" is the county-equivalent word for the state (Louisiana=parish, Alaska=borough, Puerto Rico=municipio).
const US_COUNTIES = require('./us_counties.json');
// The MUNICIPAL tier: { <USPS>: { name, places: [official incorporated-place names] } }. Generated by
// scripts/gen_us_places.js from the Census national place-by-county file (incorporated places only — the
// ones with an elected city/town/village council; CDPs are statistical, no government). New England towns
// are Census county-subdivisions (a separate future tier), so CT/RI/MA municipalities are under-counted here.
const US_PLACES = require('./us_places.json');
// The TOWN/TOWNSHIP tier: { <USPS>: { name, subdivisions: [official MCD names] } }. Generated by
// scripts/gen_us_subdivisions.js from the Census county-subdivision file (CLASSFP=T1 functioning MCD
// governments only — New England towns, NY/WI towns, and Midwest townships — the sub-county governments the
// incorporated-place tier misses). Only the 20 MCD-government states have these.
const US_SUBDIVISIONS = require('./us_subdivisions.json');
// The SCHOOL-BOARD tier: { <USPS>: { name, districts: [official school-district names] } }. Generated by
// scripts/gen_us_school_districts.js from the Census national school-district file (every public LEA; the
// board of education is elected in the large majority — the dossier surfaces the few that are appointed).
const US_SCHOOL_DISTRICTS = require('./us_school_districts.json');
// The LADDER HEAD: each state's capital + largest cities (authored from model knowledge — provenance
// in that module's header, slice B 2026-07-29). Resolved against US_PLACES at use, so a name that
// isn't a real incorporated place simply drops out (Honolulu: HI has no incorporated places).
const US_CAPITAL_CITIES = require('./us_capitals_cities');

// Back-compat: the Slice-1 exports were STATE_COUNTIES/STATE_NAMES. Derive them from the gazetteer so anything
// still importing them keeps working (STATE_COUNTIES now carries the full official names, not bare tokens).
